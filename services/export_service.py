"""
Export Service module for EduExtract AI.
Generates downloadable files in Markdown, TXT, JSON, and CSV formats,
plus comprehensive Study Packs with page references.
"""
import csv
import io
import json
from typing import Dict, Any, List

class ExportService:
    """Creates formatted downloadable files for notes, quizzes, and study packs."""

    @staticmethod
    def export_notes_markdown(doc_title: str, notes_data: Dict[str, Any], keywords: List[Dict[str, Any]]) -> str:
        """Export smart notes formatted as Markdown."""
        lines = [
            f"# Smart Study Notes: {doc_title}",
            f"**Method:** {notes_data.get('method_label', 'Extractive Summary')}  ",
            f"**Compression:** {notes_data.get('compression_ratio_pct', 0)}% reduction ({notes_data.get('summary_word_count', 0)} words)  ",
            f"**Pages Referenced:** {', '.join(map(str, notes_data.get('pages_referenced', [])))}",
            "\n---\n",
            "## Key Summary Points\n"
        ]

        for idx, s in enumerate(notes_data.get("sentences", []), 1):
            lines.append(f"{idx}. {s['text']} *(Page {s.get('page_number', 1)})*")

        lines.append("\n## Important Keywords & Concepts\n")
        for kw in keywords[:15]:
            pages = ", ".join(map(str, kw.get("pages", [])))
            lines.append(f"- **{kw['keyword']}** (Score: {kw.get('score', 0):.3f}) — Found on page(s): {pages}")

        lines.append("\n\n---\n*Generated by EduExtract AI*")
        return "\n".join(lines)

    @staticmethod
    def export_notes_txt(doc_title: str, notes_data: Dict[str, Any]) -> str:
        """Export notes as clean plain text."""
        lines = [
            f"SMART STUDY NOTES: {doc_title.upper()}",
            "=" * 60,
            f"Summary Method: {notes_data.get('method_label', '')}",
            f"Original Word Count: {notes_data.get('original_word_count', 0)}",
            f"Summary Word Count: {notes_data.get('summary_word_count', 0)}",
            f"Compression Ratio: {notes_data.get('compression_ratio_pct', 0)}%",
            "-" * 60,
            "\nSUMMARY POINTS:\n"
        ]
        for idx, s in enumerate(notes_data.get("sentences", []), 1):
            lines.append(f"[{idx}] (Page {s.get('page_number', 1)}) {s['text']}\n")

        return "\n".join(lines)

    @staticmethod
    def export_questions_json(questions: List[Dict[str, Any]]) -> str:
        """Export quiz questions and answers in JSON format."""
        clean_qs = []
        for q in questions:
            clean_qs.append({
                "question_id": q.get("question_id"),
                "question_type": q.get("question_type"),
                "question": q.get("question"),
                "options": q.get("options", []),
                "correct_answer": q.get("correct_answer"),
                "explanation": q.get("explanation"),
                "source_page": q.get("source_page"),
                "source_sentence": q.get("source_sentence"),
                "generation_method": q.get("generation_method")
            })
        return json.dumps(clean_qs, indent=2)

    @staticmethod
    def export_questions_csv(questions: List[Dict[str, Any]]) -> str:
        """Export quiz questions in CSV format."""
        output = io.StringIO()
        fieldnames = ["Question Type", "Question", "Options", "Correct Answer", "Explanation", "Source Page"]
        writer = csv.DictWriter(output, fieldnames=fieldnames)
        writer.writeheader()

        for q in questions:
            opts = "; ".join(q.get("options", [])) if q.get("options") else "N/A"
            writer.writerow({
                "Question Type": q.get("question_type", ""),
                "Question": q.get("question", ""),
                "Options": opts,
                "Correct Answer": q.get("correct_answer", ""),
                "Explanation": q.get("explanation", ""),
                "Source Page": q.get("source_page", 1)
            })

        return output.getvalue()

    @staticmethod
    def export_quiz_results_csv(score_data: Dict[str, Any]) -> str:
        """Export quiz results and detailed breakdown in CSV format."""
        output = io.StringIO()
        fieldnames = ["Question", "Your Answer", "Correct Answer", "Result", "Source Page", "Explanation"]
        writer = csv.DictWriter(output, fieldnames=fieldnames)
        writer.writeheader()

        for r in score_data.get("detailed_results", []):
            writer.writerow({
                "Question": r.get("question", ""),
                "Your Answer": r.get("user_answer", ""),
                "Correct Answer": r.get("correct_answer", ""),
                "Result": "CORRECT" if r.get("is_correct") else "INCORRECT",
                "Source Page": r.get("source_page", 1),
                "Explanation": r.get("explanation", "")
            })

        return output.getvalue()

    @staticmethod
    def export_study_pack_markdown(
        doc_title: str,
        notes_data: Dict[str, Any],
        keywords: List[Dict[str, Any]],
        questions: List[Dict[str, Any]]
    ) -> str:
        """
        Export a unified Study Pack combining smart notes, key vocabulary,
        quiz questions, and answer keys with page evidence.
        """
        pack = [
            f"# 📚 Complete Study Pack: {doc_title}",
            "Generated by **EduExtract AI**\n",
            "---\n",
            "## Part 1: Executive Study Notes",
            f"*{notes_data.get('method_label', 'Extractive Summary')}*",
            f"**Compression:** {notes_data.get('compression_ratio_pct', 0)}% | **Pages Covered:** {', '.join(map(str, notes_data.get('pages_referenced', [])))}\n"
        ]

        for idx, s in enumerate(notes_data.get("sentences", []), 1):
            pack.append(f"> **{idx}.** {s['text']}  \n> *(Source: Page {s.get('page_number', 1)})*\n")

        pack.append("\n---\n## Part 2: Key Concepts & Keywords\n")
        for kw in keywords[:15]:
            pages = ", ".join(map(str, kw.get("pages", [])))
            pack.append(f"- **{kw['keyword']}** (Score: {kw.get('score', 0):.3f}) — [Pages: {pages}]")

        pack.append("\n---\n## Part 3: Practice Quiz\n")
        for idx, q in enumerate(questions, 1):
            pack.append(f"### Q{idx} ({q.get('question_type').replace('_', ' ').title()})")
            pack.append(f"**{q.get('question')}**\n")
            if q.get("options"):
                for opt in q["options"]:
                    pack.append(f"- [ ] {opt}")
                pack.append("")
            else:
                pack.append("*Your Answer: _________________________________*\n")

        pack.append("\n---\n## Part 4: Answer Key & Evidence Grounding\n")
        for idx, q in enumerate(questions, 1):
            pack.append(f"**Q{idx} Answer:** `{q.get('correct_answer')}`")
            pack.append(f"- **Evidence:** \"{q.get('source_sentence')}\"")
            pack.append(f"- **Location:** Page {q.get('source_page', 1)}")
            pack.append(f"- **Method:** `{q.get('generation_method')}`\n")

        return "\n".join(pack)
